package io.motohub.android.routesim.experiences

/** The countries the catalogue ships with, as ISO 3166-1 alpha-2 codes. */
val CATALOG_COUNTRIES: List<String> = listOf("IT", "FR", "CH", "AT", "DE", "ES", "PT", "SI", "HR")

/**
 * Maps a position to one of [CATALOG_COUNTRIES], or null elsewhere.
 *
 * The outlines are hand-drawn and coarse (15-100 vertices a country, a few kilometres off at the
 * borders, a margin of sea off the coasts): enough to pick the right page for a rider, not to settle
 * on which side of a frontier a town lies. Where two outlines overlap the one listed first wins, so
 * the small countries come before the big ones that surround them. Islands that belong to a country
 * far from its mainland (Canaries, Madeira, Azores) are left out and give null.
 */
object CountryLocator {

    fun locate(lat: Double, lon: Double): String? {
        if (lat.isNaN() || lon.isNaN()) return null
        for (country in COUNTRIES) {
            for (outline in country.outlines) {
                if (contains(outline, lat, lon)) return country.code
            }
        }
        return null
    }

    /** Even-odd ray casting over (latitude, longitude) pairs laid out flat. */
    private fun contains(outline: DoubleArray, lat: Double, lon: Double): Boolean {
        val n = outline.size / 2
        var inside = false
        var j = n - 1
        for (i in 0 until n) {
            val latI = outline[2 * i]
            val lonI = outline[2 * i + 1]
            val latJ = outline[2 * j]
            val lonJ = outline[2 * j + 1]
            if ((lonI > lon) != (lonJ > lon) && lat < (latJ - latI) * (lon - lonI) / (lonJ - lonI) + latI) {
                inside = !inside
            }
            j = i
        }
        return inside
    }

